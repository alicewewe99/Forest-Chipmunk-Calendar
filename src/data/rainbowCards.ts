function buildRainbowCards(): RainbowCard[] {
  const cards: RainbowCard[] = [];

  const addDeck = (
    chakraKey: 'root' | 'sacral' | 'solarPlexus' | 'heart' | 'throat' | 'thirdEye' | 'crown',
    affirmations: string[]
  ) => {
    const info = CHAKRA_INFO[chakraKey];
    affirmations.forEach((aff, idx) => {
      cards.push({
        id: `rb_${chakraKey}_${idx + 1}`,
        colorName: info.colorName,
        colorHex: info.colorHex,
        bgGradient: info.bgGradient,
        chakra: info.chakra,
        chakraLocation: info.location,
        keyword: info.keyword,
        imbalanceDesc: info.imbalanceDesc,
        affirmation: aff,
        wisdom: `【${info.colorName}・${info.chakra}】對應${info.location}。象徵${info.keyword}。${info.imbalanceDesc}`,
      });
    });
  };

  addDeck('root', RED_AFFIRMATIONS);
  addDeck('sacral', ORANGE_AFFIRMATIONS);
  addDeck('solarPlexus', YELLOW_AFFIRMATIONS);
  addDeck('heart', GREEN_AFFIRMATIONS);
  addDeck('throat', BLUE_AFFIRMATIONS);
  addDeck('thirdEye', INDIGO_AFFIRMATIONS);
  addDeck('crown', VIOLET_AFFIRMATIONS);

  return cards;
}

export const ALL_RAINBOW_CARDS: RainbowCard[] = buildRainbowCards();
